"""Bundles the shared test weeks and the Python GA's saved plans into
tool/phone_benchmark/weeks.dart, so the benchmark app can run on a phone
(which cannot read ai/scenarios/). Run from the project root:

    & ai/.venv/Scripts/python.exe tool/phone_benchmark/make_weeks.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCENARIOS = ROOT / "ai" / "scenarios"
OUT = Path(__file__).resolve().parent / "weeks.dart"

rows = []
for path in sorted(SCENARIOS.glob("*.json")):
    week = json.loads(path.read_text(encoding="utf-8"))
    expected = json.loads((SCENARIOS / "expected_ga" / path.name).read_text(encoding="utf-8"))
    rows.append((json.dumps(week, separators=(",", ":")),
                 json.dumps(expected, separators=(",", ":"))))

lines = [
    "// Generated by tool/phone_benchmark/make_weeks.py. Do not edit.",
    "// Each entry: (test week JSON, Python GA's saved plan JSON).",
    "const benchmarkWeeks = <(String, String)>[",
]
for week, expected in rows:
    assert "'''" not in week + expected
    lines.append(f"  (r'''{week}''', r'''{expected}'''),")
lines.append("];")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"Wrote {len(rows)} weeks to {OUT}")
